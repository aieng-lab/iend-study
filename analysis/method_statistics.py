"""Paired statistical comparisons for the paper headline metrics.

The unit passed to Autorank is one complete ``(model, task)`` block and the
populations are method groups.  Analyses are generated by metric crossed with
one-pole/two-pole constructions.  SAE variants enter wherever the requested
metric is structurally defined; they are not excluded merely because SAE is
untargeted.

The default mode is deliberately useful before the full sweep is finished: it
keeps only listwise-complete blocks and labels every result INTERMEDIATE.  Use
``--strict`` for the final paper analysis; strict mode writes coverage
diagnostics but refuses to calculate statistics unless every structurally
comparable core block is complete.

Examples::

  python analysis/method_statistics.py
  python analysis/method_statistics.py --strict
  python analysis/method_statistics.py --source gpt2-small=suite_full2 \
      --source pythia-70m-deduped=suite_full2 --source llama-3.1-8b
"""

