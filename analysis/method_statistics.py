@dataclass(frozen=True)
class PanelData:
    metric: str
    panel: str
    methods: Tuple[str, ...]
    matrix: pd.DataFrame
    coverage: pd.DataFrame

    @property
    def n_expected(self) -> int:
        if self.coverage.empty:
            return 0
        return int(self.coverage["structurally_comparable"].sum())

    @property
    def n_complete(self) -> int:
        return int(len(self.matrix))


def _is_finite_number(value: Any) -> bool:
    if value is None or isinstance(value, bool):
        return False
    try:
        return math.isfinite(float(value))
    except (TypeError, ValueError):
        return False


def _is_true(value: Any) -> bool:
    return isinstance(value, bool) and value


def _headline_applicable(method: str, spec: Mapping[str, Any], metric: str) -> bool:
    """Apply structural rules to every constituent of a headline metric."""
    return all(
        group_is_applicable(method, spec, metric=component)
        for component in HEADLINE_COMPONENTS[metric]
    )


def _metric_value(record: Optional[Mapping[str, Any]], metric: str) -> Any:
    """Return a stored metric, deriving the neutral-only score when needed."""
    if record is None:
        return None
    if metric != "detection_light_score":
        return record.get(metric)
    auc_neutral = record.get("roc_auc_neutral")
    specificity = record.get("neutral_specificity")
    if not (_is_finite_number(auc_neutral) and _is_finite_number(specificity)):
        return None
    return min(float(auc_neutral), float(specificity))


def parse_sources(values: Optional[Sequence[str]]) -> Tuple[Tuple[str, str], ...]:
    """Parse repeatable ``MODEL[=OUTPUT_SUBDIR]`` command-line values."""
    if not values:
        return DEFAULT_CROSS_MODEL_SOURCES
    parsed: List[Tuple[str, str]] = []
    seen: set[str] = set()
    for raw in values:
        model, separator, subdir = str(raw).partition("=")
        model = model.strip()
        subdir = subdir.strip() if separator else ""
        if not model:
            raise ValueError(f"invalid empty model in --source {raw!r}")
        if model in seen:
            raise ValueError(f"duplicate --source model {model!r}")
        if subdir and (Path(subdir).is_absolute() or ".." in Path(subdir).parts):
            raise ValueError(f"OUTPUT_SUBDIR must be a relative child name: {subdir!r}")
        seen.add(model)
        parsed.append((model, subdir))
    return tuple(parsed)


