def parse_csv_sources(values: Sequence[str]) -> Tuple[Tuple[str, Path], ...]:
    """Parse normalized local summary inputs for the efficient Autorank path."""
    parsed: List[Tuple[str, Path]] = []
    seen: set[str] = set()
    for raw in values:
        model, separator, raw_path = str(raw).partition("=")
        model, raw_path = model.strip(), raw_path.strip()
        if not separator or not model or not raw_path:
            raise ValueError("--csv must be MODEL=PATH_TO_summary_merged.csv")
        if model in seen:
            raise ValueError(f"duplicate --csv model {model!r}")
        path = Path(raw_path)
        if not path.is_file():
            raise ValueError(f"missing --csv input: {path}")
        seen.add(model)
        parsed.append((model, path))
    return tuple(parsed)


def load_csv_frames(csv_sources: Sequence[Tuple[str, Path]]) -> Dict[str, pd.DataFrame]:
    """Load canonical summary rows without reopening any results.json files."""
    frames: Dict[str, pd.DataFrame] = {}
    for model, path in csv_sources:
        frame = pd.read_csv(path)
        frame["model"] = model
        frames[model] = frame
    return frames


def _row_lookup(frame: pd.DataFrame) -> Dict[Tuple[str, str], Mapping[str, Any]]:
    if frame.empty:
        return {}
    required = {"task", "method_group"}
    if not required.issubset(frame.columns):
        return {}
    lookup: Dict[Tuple[str, str], Mapping[str, Any]] = {}
    for record in frame.to_dict(orient="records"):
        key = (str(record["task"]), str(record["method_group"]))
        if key in lookup:
            raise ValueError(f"duplicate canonical result row for task/method {key}")
        lookup[key] = record
    return lookup


def build_panel_data(
    frames: Mapping[str, pd.DataFrame],
    *,
    sources: Sequence[Tuple[str, str]],
    metric: str,
    panel: str,
    tasks: Sequence[str] = PAPER_TASK_ORDER,
    methods: Optional[Sequence[str]] = None,
) -> PanelData:
    """Build a listwise-complete paired matrix and block-level audit table."""
    if metric not in METRICS:
        raise ValueError(f"metric must be one of {METRICS}, got {metric!r}")
    if panel not in PANELS:
        raise ValueError(f"panel must be one of {PANELS}, got {panel!r}")
    selected_methods = tuple(methods or CORE_PANEL_METHODS[panel])
    if len(selected_methods) < 2:
        raise ValueError("at least two methods are required")
    labels = [METHOD_DISPLAY.get(method, method) for method in selected_methods]
    if len(set(labels)) != len(labels):
        raise ValueError(f"Autorank display labels are not unique: {labels}")

    complete_field = {
        "detection_score": "detection_complete",
        "detection_light_score": "detection_complete",
        "intervention_score": "intervention_complete",
    }[metric]
    visible_tasks = [str(task) for task in tasks if str(task) not in HIDDEN_MATRIX_TASKS]
    lookups = {model: _row_lookup(frames.get(model, pd.DataFrame())) for model, _ in sources}
    matrix_rows: List[Dict[str, Any]] = []
    matrix_index: List[Tuple[str, str]] = []
    coverage_rows: List[Dict[str, Any]] = []

    for model, subdir in sources:
        lookup = lookups[model]
        for task in visible_tasks:
            spec = spec_for_task(task, suite="core", model=model)
            applicable = {
                method: _headline_applicable(method, spec, metric)
                for method in selected_methods
            }
            structurally_comparable = all(applicable.values())
            missing: List[str] = []
            incomplete: List[str] = []
            bad_status: List[str] = []
            values: Dict[str, float] = {}

            if structurally_comparable:
                for method in selected_methods:
                    record = lookup.get((task, method))
                    value = _metric_value(record, metric) if record is not None else None
                    if not _is_finite_number(value):
                        missing.append(method)
                        continue
                    if str(record.get("run_status", "")).lower() != "ok":
                        bad_status.append(method)
                        continue
                    if not _is_true(record.get(complete_field)):
                        incomplete.append(method)
                        continue
                    values[method] = float(value)

            complete = structurally_comparable and len(values) == len(selected_methods)
            coverage_rows.append(
                {
                    "metric": metric,
                    "panel": panel,
                    "model": model,
                    "subdir": subdir or None,
                    "task": task,
                    "structurally_comparable": structurally_comparable,
                    "complete": complete,
                    "n_methods": len(selected_methods),
                    "n_available": len(values),
                    "structural_methods": ";".join(
                        method for method, is_applicable in applicable.items() if not is_applicable
                    ),
                    "missing_methods": ";".join(missing),
                    "raw_incomplete_methods": ";".join(incomplete),
                    "non_ok_methods": ";".join(bad_status),
                }
            )
            if complete:
                matrix_index.append((model, task))
                matrix_rows.append(values)

    matrix = pd.DataFrame(matrix_rows, columns=selected_methods)
    matrix.index = pd.MultiIndex.from_tuples(matrix_index, names=["model", "task"])
    coverage = pd.DataFrame(coverage_rows)
    return PanelData(
        metric=metric,
        panel=panel,
        methods=selected_methods,
        matrix=matrix,
        coverage=coverage,
    )


def select_intermediate_panel(
    frames: Mapping[str, pd.DataFrame],
    *,
    sources: Sequence[Tuple[str, str]],
    metric: str,
    panel: str,
    tasks: Sequence[str] = PAPER_TASK_ORDER,
    methods: Optional[Sequence[str]] = None,
    min_blocks: int = MIN_AUTORANK_BLOCKS,
) -> Tuple[PanelData, Tuple[str, ...]]:
    """Select the largest coherent method ranking available during a sweep.

    Selection uses coverage only, never metric values: maximize the number of
    jointly ranked methods first, then the number of common complete blocks.
    The final ``--strict`` path does not call this function and always requires
    the full predeclared core panel.
    """
    requested = tuple(methods or CORE_PANEL_METHODS[panel])
    full = build_panel_data(
        frames,
        sources=sources,
        metric=metric,
        panel=panel,
        tasks=tasks,
        methods=requested,
    )
    if full.n_complete >= min_blocks:
        return full, ()

    for size in range(len(requested) - 1, 1, -1):
        candidates: List[PanelData] = []
        for subset in combinations(requested, size):
            candidate = build_panel_data(
                frames,
                sources=sources,
                metric=metric,
                panel=panel,
                tasks=tasks,
                methods=subset,
            )
            if candidate.n_complete >= min_blocks:
                candidates.append(candidate)
        if candidates:
            chosen = max(candidates, key=lambda candidate: candidate.n_complete)
            excluded = tuple(method for method in requested if method not in chosen.methods)
            return chosen, excluded
    return full, ()


def _capture_call(function: Any, *args: Any, **kwargs: Any) -> str:
    stream = io.StringIO()
    with contextlib.redirect_stdout(stream):
        function(*args, **kwargs)
    return stream.getvalue()


def _safe_float(value: Any) -> Optional[float]:
    return float(value) if _is_finite_number(value) else None


def build_descriptive_leaderboard(panel_data: PanelData) -> pd.DataFrame:
    """Rank methods on every available complete block, even when n < 5."""
    columns = [
        "position",
        "method_group",
        "display_name",
        "mean_rank",
        "mean",
        "median",
        "n_blocks",
    ]
    if panel_data.matrix.empty:
        return pd.DataFrame(columns=columns)
    per_block_ranks = panel_data.matrix.rank(axis=1, ascending=False, method="average")
    leaderboard = pd.DataFrame(
        {
            "method_group": list(panel_data.methods),
            "display_name": [
                METHOD_DISPLAY.get(method, method) for method in panel_data.methods
            ],
            "mean_rank": [float(per_block_ranks[method].mean()) for method in panel_data.methods],
            "mean": [float(panel_data.matrix[method].mean()) for method in panel_data.methods],
            "median": [float(panel_data.matrix[method].median()) for method in panel_data.methods],
            "n_blocks": len(panel_data.matrix),
        }
    )
    leaderboard["position"] = (
        leaderboard["mean_rank"].rank(method="min", ascending=True).astype(int)
    )
    return leaderboard.sort_values(
        ["mean_rank", "median", "method_group"], ascending=[True, False, True]
    ).reindex(columns=columns)


def build_bayesian_outcomes(
    posterior: pd.DataFrame,
    *,
    label_to_method: Mapping[str, str],
    alpha: float,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Convert Autorank's posterior tuples into explicit A-vs-B outcomes.

    An upper-triangle cell stores ``P(row > column), P(ROPE), P(row < column)``
    for a descending metric.  The output never calls an inconclusive comparison
    equal: practical equivalence requires posterior probability >= 1-alpha.
    """
    labels = [str(label) for label in posterior.index]
    decisions = pd.DataFrame("same method", index=labels, columns=labels)
    rows: List[Dict[str, Any]] = []
    threshold = 1.0 - alpha
    for left_index, left in enumerate(labels):
        for right in labels[left_index + 1 :]:
            probabilities = posterior.loc[left, right]
            reversed_cell = False
            if not isinstance(probabilities, tuple):
                probabilities = posterior.loc[right, left]
                reversed_cell = True
            if not isinstance(probabilities, tuple) or len(probabilities) != 3:
                raise ValueError(f"missing Bayesian posterior for {left!r} vs {right!r}")
            p_left_better, p_equivalent, p_right_better = map(float, probabilities)
            if reversed_cell:
                p_left_better, p_right_better = p_right_better, p_left_better

            if p_left_better >= threshold:
                left_decision, right_decision = "better", "worse"
            elif p_equivalent >= threshold:
                left_decision = right_decision = "practically equivalent"
            elif p_right_better >= threshold:
                left_decision, right_decision = "worse", "better"
            else:
                left_decision = right_decision = "inconclusive"
            decisions.loc[left, right] = left_decision
            decisions.loc[right, left] = right_decision
            rows.append(
                {
                    "method_a": label_to_method[left],
                    "method_b": label_to_method[right],
                    "display_a": left,
                    "display_b": right,
                    "p_a_better": p_left_better,
                    "p_practically_equivalent": p_equivalent,
                    "p_b_better": p_right_better,
                    "decision_a_vs_b": left_decision,
                }
            )
    decisions.index.name = "A_vs_B"
    return pd.DataFrame(rows), decisions


def posterior_probability_matrices(posterior: pd.DataFrame) -> Dict[str, pd.DataFrame]:
    """Materialize Autorank's posterior tuples as A-vs-B probability matrices.

    The row method is A and the column method is B throughout.  This makes
    the heatmap directions explicit rather than depending on Autorank's
    upper-triangle storage convention.
    """
    labels = [str(label) for label in posterior.index]
    matrices = {
        "a_better": pd.DataFrame(float("nan"), index=labels, columns=labels),
        "equivalent": pd.DataFrame(float("nan"), index=labels, columns=labels),
        "b_better": pd.DataFrame(float("nan"), index=labels, columns=labels),
    }
    for left in labels:
        for right in labels:
            if left == right:
                continue
            probabilities = posterior.loc[left, right]
            reversed_cell = False
            if not isinstance(probabilities, tuple):
                probabilities = posterior.loc[right, left]
                reversed_cell = True
            if not isinstance(probabilities, tuple) or len(probabilities) != 3:
                raise ValueError(f"missing Bayesian posterior for {left!r} vs {right!r}")
            p_left, p_equal, p_right = map(float, probabilities)
            if reversed_cell:
                p_left, p_right = p_right, p_left
            matrices["a_better"].loc[left, right] = p_left
            matrices["equivalent"].loc[left, right] = p_equal
            matrices["b_better"].loc[left, right] = p_right
    return matrices


def write_bayesian_posterior_maps(
    posterior: pd.DataFrame,
    decisions: pd.DataFrame,
    path: Path,
) -> Path:
    """Write the four Bayesian Autorank posterior/decision heatmaps."""
    import matplotlib.pyplot as plt
    import numpy as np
    from matplotlib.colors import ListedColormap
    from matplotlib.patches import Patch

    probabilities = posterior_probability_matrices(posterior)
    labels = list(probabilities["a_better"].index)
    figure, axes = plt.subplots(2, 2, figsize=(10.4, 9.0), constrained_layout=True)
    probability_specs = (
        ("a_better", r"$P(A > B)$"),
        ("equivalent", r"$P(A = B)$"),
        ("b_better", r"$P(A < B)$"),
    )
    for axis, (key, title) in zip(axes.flat[:3], probability_specs):
        values = probabilities[key].to_numpy(dtype=float)
        image = axis.imshow(values, cmap="Blues", vmin=0.0, vmax=1.0, aspect="equal")
        for row, col in zip(*np.where(np.isfinite(values))):
            value = values[row, col]
            axis.text(col, row, f"{value:.2f}", ha="center", va="center", fontsize=7.5,
                      color="white" if value >= 0.62 else "#0b0b0b")
        axis.set_title(title)
        axis.set_xticks(range(len(labels)), labels, rotation=35, ha="right", fontsize=7.5)
        axis.set_yticks(range(len(labels)), labels, fontsize=7.5)
        axis.set_xlabel("B")
        axis.set_ylabel("A")
        figure.colorbar(image, ax=axis, fraction=0.046, pad=0.04, label="posterior probability")

    decision_axis = axes.flat[3]
    decision_codes = {
        "better": 0,
        "practically equivalent": 1,
        "worse": 2,
        "inconclusive": 3,
        "same method": 4,
    }
    decision_text = {0: ">", 1: "=", 2: "<", 3: "?", 4: ""}
    values = decisions.reindex(index=labels, columns=labels).apply(
        lambda column: column.map(decision_codes)
    ).to_numpy(dtype=float)
    colors = ["#4c78a8", "#b8b8b8", "#f58518", "#ffffff", "#ececec"]
    decision_axis.imshow(values, cmap=ListedColormap(colors), vmin=0, vmax=len(colors) - 1, aspect="equal")
    for row, col in np.ndindex(values.shape):
        code = int(values[row, col])
        decision_axis.text(col, row, decision_text[code], ha="center", va="center", fontsize=9,
                           color="white" if code in {0, 2} else "#0b0b0b")
    decision_axis.set_title("Bayesian decision for A relative to B")
    decision_axis.set_xticks(range(len(labels)), labels, rotation=35, ha="right", fontsize=7.5)
    decision_axis.set_yticks(range(len(labels)), labels, fontsize=7.5)
    decision_axis.set_xlabel("B")
    decision_axis.set_ylabel("A")
    decision_axis.legend(
        handles=[
            Patch(color=colors[0], label="A better"),
            Patch(color=colors[1], label="practically equivalent"),
            Patch(color=colors[2], label="A worse"),
            Patch(color=colors[3], label="inconclusive"),
        ],
        loc="upper center", bbox_to_anchor=(0.5, -0.19), ncol=2,
        frameon=True, fontsize=7.5,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(path, bbox_inches="tight")
    plt.close(figure)
    return path


def _write_outcome_markdown(
    path: Path,
    *,
    panel_data: PanelData,
    ranks: pd.DataFrame,
    decisions: pd.DataFrame,
    n_expected: int,
    rope: float,
    alpha: float,
    strict: bool,
    excluded_methods: Sequence[str] = (),
) -> None:
    mode = "FINAL STRICT" if strict else "INTERMEDIATE COMPLETE-CASE"
    lines = [
        f"# {panel_data.metric.removesuffix('_score').title()} — "
        f"{panel_data.panel.replace('_', '-')}",
        "",
        f"**{mode}: {len(panel_data.matrix)}/{n_expected} complete `(model, task)` blocks.**",
        "",
        *(
            [
                "Coverage-only interim selection excluded: "
                + ", ".join(METHOD_DISPLAY.get(method, method) for method in excluded_methods)
                + ".",
                "",
            ]
            if excluded_methods
            else []
        ),
        "## Ranking",
        "",
        "Lower mean rank is better.",
        "",
        "| Position | Method | Mean rank | Median |",
        "|---:|---|---:|---:|",
    ]
    for display_name, row in ranks.iterrows():
        lines.append(
            f"| {int(row['position'])} | {display_name} | "
            f"{float(row['meanrank']):.3f} | {float(row['median']):.3f} |"
        )
    lines.extend(
        [
            "",
            "## Bayesian A-vs-B outcome",
            "",
            f"Absolute ROPE: ±{rope:.3f}; decision threshold: {1-alpha:.0%}. "
            "`Practically equivalent` is an affirmative equivalence result; "
            "`inconclusive` is not equality.",
            "",
            "Rows state the outcome of method A relative to column method B.",
            "",
            "| A \\ B | " + " | ".join(str(column) for column in decisions.columns) + " |",
            "|---|" + "---|" * len(decisions.columns),
        ]
    )
    for label, row in decisions.iterrows():
        lines.append(f"| {label} | " + " | ".join(str(value) for value in row) + " |")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


